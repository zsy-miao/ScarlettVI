#pragma once
#include <cstddef>
#include <cstdint>
#include <span>

namespace scarlett::analysis {

// Research-only projection of unambiguous stores in the three verified
// category branches and common initial stores in a title-side descriptor
// helper. NOT an Xbox XG ABI or a complete descriptor/import implementation.
enum class XgFieldProjectionStatus {
    ok,
    truncated_input,
    truncated_output,
    overlapping_buffers
};
inline constexpr size_t kXgCompactObservedInputExtent = 0x0B;
inline constexpr size_t kXgPreparedObservedOutputExtent = 0x30;

struct XgObservedCompactFields {
    uint8_t category_06 = 0;
    uint16_t source_00 = 0;
    uint16_t source_02 = 0;
    uint16_t source_04 = 0;
    uint8_t source_07 = 0;
    uint8_t source_0a = 0;
};

// Do not assign semantic names to offsets; field meanings are unknown.
// Invalid input leaves 'result' unchanged.
XgFieldProjectionStatus decode_xg_observed_fields(
    std::span<const uint8_t> compact,
    XgObservedCompactFields& result) noexcept;

// Tracks whether the unknown format-lookup value at +0x24 could be
// projected without reading the title's proprietary lookup table.
struct XgFieldProjectionCoverage {
    bool output_24_known = false;
    size_t modeled_bytes = 0;
};

// Projects only independently corroborated initial stores: output +0x00,
// +0x08, +0x10..+0x23, +0x28 and sometimes +0x24. All other bytes are
// untouched. +0x24 is deliberately preserved for the unverified lookup
// index range (compact +0x09 in [1,17], nonzero/non-3 categories).
// The final descriptor may be modified by later unmodeled paths.
// No import binding, title execution, or title-byte copying.
// On error both output and coverage are unchanged.
XgFieldProjectionStatus project_xg_observed_fields(
    std::span<const uint8_t> compact,
    std::span<uint8_t> prepared,
    XgFieldProjectionCoverage* coverage = nullptr) noexcept;

// Only independently generated byte fixtures; no title instructions or assets.
bool verify_xg_field_projection_fixtures() noexcept;
} // namespace scarlett::analysis
